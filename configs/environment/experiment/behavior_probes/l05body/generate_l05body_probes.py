"""Generate experiment-test scenes for the level-05 body-rules factorial -- 16 worlds x 12 scenes.

WHAT THIS IS FOR. The cross-run "Figure 7b" page (docs/experiments/active/hypervigilance/
f7b_across_runs/) compares bush dwell in the 12 fixed test scenes across many trained agents.
The 32 agents of the level-05 body-rules factorial (configs/environment/experiment/
level05_body_interactions/worlds/w*.yaml: 4 on/off body rules, 16 worlds x 2 agents) had no
experiment tests. This builds the SAME 12 scenes the smell study used (behavior_probes/hvsmell/
two_channel/), but on top of each body world, so each agent meets the body rules it trained with.

HOW EACH FILE IS BUILT. Take the smell study's control-world scene (two_channel/<scene>.yaml,
itself the core avoidance probe + one campfire beside the bush), and change ONLY its `extends:`
target from the control smell world to the body world `level05_body_interactions/worlds/w<code>`.
Both of those extend basic/05 and the control smell world restates basic/05's odours, so w0000's
scenes load to the same parameters as the two_channel scenes -- asserted below. Everything the
scene states (grid, start, bush that hides the agent and blocks animals, campfire, animal, no food,
100 steps, start injury 0 or 70) is unchanged; everything it does not state (the body rules) comes
from the body world.

Writes <here>/w<code>/avoid_*.yaml and the sweep specs configs/eval_sweeps/l05body/l05body_w<code>_rppo.yaml.

  /home/vncuser/miniconda3/envs/grid_world_pain/bin/python \
      configs/environment/experiment/behavior_probes/l05body/generate_l05body_probes.py [--check-only]
"""
import argparse
import glob
import os
import sys

import numpy as np

_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), *(['..'] * 5)))
sys.path.insert(0, _ROOT)
os.chdir(_ROOT)

from src.environment.config_loader import load_env_config, load_env_params  # noqa: E402

HERE = 'configs/environment/experiment/behavior_probes/l05body'
SRC = 'configs/environment/experiment/behavior_probes/hvsmell/two_channel'
SRC_EXTENDS = 'extends: environment/experiment/hypervigilance/two_channel_smell_l05_control'
SPEC_DIR = 'configs/eval_sweeps/l05body'
WORLDS = sorted(os.path.basename(p)[:-5] for p in
                glob.glob('configs/environment/experiment/level05_body_interactions/worlds/w*.yaml'))
RUNS = 'results/JAX_RecurrentPPO'


def scene_text(world, src_path):
    txt = open(src_path).read()
    assert txt.count(SRC_EXTENDS) == 1, src_path
    head = (f"# L05BODY EXPERIMENT TEST -- world {world}, scene {os.path.basename(src_path)[:-5]}\n"
            f"# GENERATED by {HERE}/generate_l05body_probes.py -- do not hand-edit.\n"
            f"# = {src_path} with `extends:` pointed at the body world {world}.\n")
    return head + txt.replace(SRC_EXTENDS, f'extends: environment/experiment/level05_body_interactions/worlds/{world}')


def params(path):
    return load_env_params(load_env_config(path))


def flat(p):
    """Every field of a loaded EnvParams, as comparable Python values."""
    out = {}
    for k in p.__dataclass_fields__:
        v = getattr(p, k)
        try:
            out[k] = np.asarray(v).tolist()
        except Exception:
            out[k] = repr(v)
    return out


def obs_width(p):
    import jax
    from src.environment.wrapper import ParallelEnv
    _, obs = ParallelEnv(p).reset(jax.random.PRNGKey(0), 1)
    return int(obs.shape[-1])


def run_dirs(world):
    out = {}
    for agent in ('t1none', 't16quad'):
        m = sorted(glob.glob(f'{RUNS}/2026*_rppo_l05body_{world}_{agent}_s42'))
        assert len(m) == 1, (world, agent, m)
        out[agent] = m[0]
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check-only', action='store_true')
    a = ap.parse_args()
    srcs = sorted(glob.glob(f'{SRC}/avoid_*.yaml'))
    assert len(srcs) == 12, srcs
    os.makedirs(SPEC_DIR, exist_ok=True)
    for w in WORLDS:
        d = f'{HERE}/{w}'
        os.makedirs(d, exist_ok=True)
        for s in srcs:
            path = f'{d}/{os.path.basename(s)}'
            txt = scene_text(w, s)
            if a.check_only:
                assert open(path).read() == txt, path
            else:
                open(path, 'w').write(txt)
        rd = run_dirs(w)
        spec = (f"# Experiment-test sweep, level-05 body-rules factorial, world {w} (both agents, seed 42).\n"
                f"# GENERATED by {HERE}/generate_l05body_probes.py. Scenes: {d}/ (12 scenes, see generator).\n"
                f"# nodes: filled at launch from live state.\n"
                f"name: l05body_{w}\nalgo: rppo\noutput_dir: results/eval/avoidance/metrics_history_rppo_l05body/{w}\n"
                f"probe: {d}\nconditions: all\nepisodes: 30\nnodes: []\nx_axis: steps\n"
                f"plot_measures: [bush_hiding, spatial_spread, survival_steps]\nruns:\n"
                f"  - {{label: {w}_ordinary_s42, path: {rd['t1none']}}}\n"
                f"  - {{label: {w}_modulated_s42, path: {rd['t16quad']}}}\n")
        sp = f'{SPEC_DIR}/l05body_{w}_rppo.yaml'
        if a.check_only:
            assert open(sp).read() == spec, sp
        else:
            open(sp, 'w').write(spec)
    # w0000 scenes must load to the same parameters as the smell study's control scenes.
    for s in srcs:
        ref = flat(params(s))
        new = flat(params(f'{HERE}/w0000/{os.path.basename(s)}'))
        diff = [k for k in ref if ref[k] != new.get(k)]
        assert not diff, (s, diff[:10])
    # every scene loads; observation width is the trained 58
    for w in WORLDS:
        for s in srcs:
            p = params(f'{HERE}/{w}/{os.path.basename(s)}')
        ow = obs_width(p)
        assert ow == 58, (w, ow)
    print(f'ok: {len(WORLDS)} worlds x {len(srcs)} scenes; w0000 == two_channel (all {len(srcs)} scenes)')


if __name__ == '__main__':
    main()
