"""Write a THERMAL-NEUTRAL copy of a study's own probe scenes.

WHY THIS EXISTS. The 22-Sep level-05 runs were tested in the thermal battery's `neutral` arm (air 0 C
everywhere, no campfire, body temperature starting at 0); every later study (smell, body rules, thirst)
was tested only in its own scenes (the study world's cold air, a campfire beside the bush, the world's
random start temperature). The two sets cannot be compared (docs/llm_wiki/entries/behavior_measures/
20261006_0758_test_scene_confound_level05_modulator_gap.md). This writes, for any folder of own-world
scenes, a copy that changes ONLY the temperature parts, exactly as the thermal battery's neutral arm does:

  thermal.default_temp           -> [0.0, 0.0]
  thermal.random_start_body_temp -> false, start_body_temp_low/high -> 0.0
  environment.obstacles          -> the scene's own list minus every campfire

Each output file `extends:` its source scene, so everything else (the study world's smell, body rules,
pond, map) is inherited unchanged. `Config.merge` replaces lists wholesale, so the obstacle list is
restated in full without the campfire.

CHECK (--check): the copy of hvsmell/two_channel must resolve, key for key, to the existing
thermal/neutral_clean scenes (the level-05 world in both) -- the proof that this reproduces the arm.

  $P configs/environment/experiment/behavior_probes/neutral_variants/generate_neutral_variants.py \
      --src behavior_probes/hvsmell/two_channel [--src ...] [--check]
Output: neutral_variants/<src path with / replaced by __>/<scene>.yaml
"""
import argparse
import glob
import os
import sys

import yaml

_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), *(['..'] * 5)))
sys.path.insert(0, _ROOT)
os.chdir(_ROOT)
from src.environment.config_loader import load_env_config   # noqa: E402

BASE = 'configs/environment/experiment'
OUT = f'{BASE}/behavior_probes/neutral_variants'
GEN = f'{OUT}/generate_neutral_variants.py'


def resolved(path):
    c = load_env_config(path)
    d = next(getattr(c, a) for a in ('to_dict', '_data', 'data', 'config', '_config') if hasattr(c, a))
    return d() if callable(d) else d


def write_variant(src_file, out_file):
    rel = os.path.relpath(src_file, 'configs')[:-len('.yaml')]
    obstacles = [o for o in resolved(src_file)['environment']['obstacles'] if o.get('name') != 'campfire']
    d = {'extends': rel,
         'thermal': {'default_temp': [0.0, 0.0], 'random_start_body_temp': False,
                     'start_body_temp_low': 0.0, 'start_body_temp_high': 0.0},
         'environment': {'obstacles': obstacles}}
    head = (f"# THERMAL-NEUTRAL copy of {src_file}\n# GENERATED by {GEN} -- do not hand-edit.\n"
            "# Changes only: air 0 C everywhere, start body temperature fixed at 0, campfire removed\n"
            "# (the thermal battery's `neutral` arm). Everything else is the source scene's.\n")
    with open(out_file, 'w') as fh:
        fh.write(head)
        yaml.safe_dump(d, fh, sort_keys=False)


def flat(d, p=''):
    o = {}
    if isinstance(d, dict):
        for k, v in d.items():
            o.update(flat(v, f'{p}.{k}' if p else str(k)))
    else:
        o[p] = d
    return o


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--src', action='append', required=True, help='folder under configs/environment/experiment/')
    ap.add_argument('--check', action='store_true', help='compare the hvsmell/two_channel copy with thermal/neutral_clean')
    a = ap.parse_args()
    n = 0
    for src in a.src:
        out_dir = os.path.join(OUT, src.replace('behavior_probes/', '').replace('/', '__'))
        os.makedirs(out_dir, exist_ok=True)
        for f in sorted(glob.glob(os.path.join(BASE, src, 'avoid_*.yaml'))):
            o = os.path.join(out_dir, os.path.basename(f))
            write_variant(f, o)
            r = flat(resolved(o))
            assert r['thermal.default_temp'] == [0.0, 0.0] and r['thermal.random_start_body_temp'] is False, o
            assert not any(x.get('name') == 'campfire' for x in resolved(o)['environment']['obstacles']), o
            n += 1
        print(f'{src}: {len(glob.glob(os.path.join(out_dir, "avoid_*.yaml")))} files -> {out_dir}')
    if a.check:
        bad = 0
        for f in sorted(glob.glob(os.path.join(OUT, 'hvsmell__two_channel', 'avoid_*.yaml'))):
            ref = os.path.join(BASE, 'behavior_probes/thermal/neutral_clean', os.path.basename(f))
            A, B = flat(resolved(f)), flat(resolved(ref))
            diff = [k for k in set(A) | set(B) if A.get(k) != B.get(k)]
            bad += bool(diff)
            print(f'  check {os.path.basename(f)}: {"identical" if not diff else "DIFFERS: " + ", ".join(sorted(diff)[:6])}')
        print('CHECK PASSED' if not bad else f'CHECK FAILED ({bad} files)')
        return 1 if bad else 0
    print(f'{n} files written')
    return 0


if __name__ == '__main__':
    sys.exit(main())
