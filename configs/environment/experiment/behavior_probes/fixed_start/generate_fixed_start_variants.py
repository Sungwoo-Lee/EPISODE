"""Write a FIXED-START-TEMPERATURE copy of a study's own probe scenes.

WHY THIS EXISTS. The level-05 fixed-start arm of the fast-heal replication (FAST_HEAL_REPLICATION.md,
world configs/environment/experiment/hypervigilance/fixed_start_temp_l05.yaml) trains with
`thermal.random_start_body_temp: false`, so every episode starts at the temperature setpoint. The
level-05 "own" test scenes (behavior_probes/hvsmell/two_channel) inherit the level-05 random start
(-10..+5 C), which those agents never saw. This writes, for a folder of scenes, a copy that changes ONLY
that one key -- exactly the training world's override -- so the fixed-start runs can be tested in their
own scenes. Each output file `extends:` its source scene, so everything else is inherited unchanged.

  $P configs/environment/experiment/behavior_probes/fixed_start/generate_fixed_start_variants.py \
      --src behavior_probes/hvsmell/two_channel [--check]
Output: fixed_start/<src path with / replaced by __>/<scene>.yaml
"""
import argparse
import glob
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", "..", "..", ".."))

BODY = """# GENERATED by configs/environment/experiment/behavior_probes/fixed_start/generate_fixed_start_variants.py
# -- do not edit. Source scene: {src}. Changes ONLY the start body temperature to the training
# world's fixed start (configs/environment/experiment/hypervigilance/fixed_start_temp_l05.yaml).
extends: environment/experiment/{src_noext}

thermal:
  random_start_body_temp: false
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", action="append", required=True)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    sys.path.insert(0, ROOT)
    for src in a.src:
        files = sorted(glob.glob(os.path.join(ROOT, "configs/environment/experiment", src, "*.yaml")))
        if not files:
            raise SystemExit(f"no scenes under {src}")
        out = os.path.join(HERE, src.replace("behavior_probes/", "").replace("/", "__"))
        os.makedirs(out, exist_ok=True)
        for f in files:
            rel = os.path.relpath(f, os.path.join(ROOT, "configs/environment/experiment"))
            text = BODY.format(src=rel, src_noext=rel[:-5])
            dst = os.path.join(out, os.path.basename(f))
            if a.check:
                if open(dst).read() != text:
                    raise SystemExit(f"drift: {dst}")
            else:
                open(dst, "w").write(text)
        print(f"{'checked' if a.check else 'wrote'} {len(files)} scenes -> {os.path.relpath(out, ROOT)}")
        if a.check:      # each copy must resolve to its source in every key except the start temperature
            from src.environment.config_loader import load_env_config
            for f in files:
                s = load_env_config(f).to_dict() if hasattr(load_env_config(f), "to_dict") else None
                d = load_env_config(os.path.join(out, os.path.basename(f)))
                d = d.to_dict() if hasattr(d, "to_dict") else None
                if s is None or d is None:
                    raise SystemExit("cannot compare resolved configs")
                diff = sorted(_diff(s, d))
                if diff != ["thermal.random_start_body_temp"]:
                    raise SystemExit(f"{os.path.basename(f)}: differs from its source in {diff}")
            print(f"  each copy differs from its source only in thermal.random_start_body_temp")


def _diff(a, b, p=""):
    keys = set(a) | set(b)
    for k in keys:
        q = f"{p}{k}"
        if k not in a or k not in b:
            yield q
        elif isinstance(a[k], dict) and isinstance(b[k], dict):
            yield from _diff(a[k], b[k], q + ".")
        elif a[k] != b[k]:
            yield q


if __name__ == "__main__":
    main()
