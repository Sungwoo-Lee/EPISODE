"""Write a NO-HEALING copy of a folder of probe scenes.

WHY THIS EXISTS. In the test scenes an agent that starts injured (e.g. injury 70) walks to the bush and,
with the training worlds' 25x bush healing (body.recovery_in_bush_multiplier 25, base rate 0.2), heals
about 5 points per step, so the "injured" condition lasts only ~10-15 of the 100 steps (seen in recorded
test videos, 2026-10-07). This writes a copy of a folder of scenes that changes ONLY
body.recovery_base_rate -> 0.0 (no healing anywhere), so the starting injury holds for the whole episode.
Each output file `extends:` its source scene, so everything else is inherited unchanged.

  $P configs/environment/experiment/behavior_probes/no_healing/generate_no_healing_variants.py \
      --src behavior_probes/thermal/neutral_clean [--src ...] [--check]
Output: no_healing/<src path with / replaced by __>/<scene>.yaml
"""
import argparse
import glob
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", "..", "..", ".."))

BODY = """# GENERATED by configs/environment/experiment/behavior_probes/no_healing/generate_no_healing_variants.py
# -- do not edit. Source scene: {src}. Changes ONLY body.recovery_base_rate -> 0.0 (no healing),
# so the starting injury holds for the whole test episode.
extends: environment/experiment/{src_noext}

body:
  recovery_base_rate: 0.0
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", action="append", required=True)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    sys.path.insert(0, ROOT)
    for src in a.src:
        files = sorted(glob.glob(os.path.join(ROOT, "configs/environment/experiment", src, "*.yaml")))
        if not files:
            raise SystemExit(f"no scenes under {src}")
        out = os.path.join(HERE, src.replace("behavior_probes/", "").replace("/", "__"))
        os.makedirs(out, exist_ok=True)
        for f in files:
            rel = os.path.relpath(f, os.path.join(ROOT, "configs/environment/experiment"))
            text = BODY.format(src=rel, src_noext=rel[:-5])
            dst = os.path.join(out, os.path.basename(f))
            if a.check:
                if open(dst).read() != text:
                    raise SystemExit(f"drift: {dst}")
            else:
                open(dst, "w").write(text)
        print(f"{'checked' if a.check else 'wrote'} {len(files)} scenes -> {os.path.relpath(out, ROOT)}")
        if a.check:      # each copy must resolve to its source in every key except the start temperature
            from src.environment.config_loader import load_env_config
            for f in files:
                s = load_env_config(f).to_dict() if hasattr(load_env_config(f), "to_dict") else None
                d = load_env_config(os.path.join(out, os.path.basename(f)))
                d = d.to_dict() if hasattr(d, "to_dict") else None
                if s is None or d is None:
                    raise SystemExit("cannot compare resolved configs")
                diff = sorted(_diff(s, d))
                if diff != ["body.recovery_base_rate"]:
                    raise SystemExit(f"{os.path.basename(f)}: differs from its source in {diff}")
            print(f"  each copy differs from its source only in body.recovery_base_rate")


def _diff(a, b, p=""):
    keys = set(a) | set(b)
    for k in keys:
        q = f"{p}{k}"
        if k not in a or k not in b:
            yield q
        elif isinstance(a[k], dict) and isinstance(b[k], dict):
            yield from _diff(a[k], b[k], q + ".")
        elif a[k] != b[k]:
            yield q


if __name__ == "__main__":
    main()
