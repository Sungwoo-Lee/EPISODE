"""The V2 render entry point writes videos WITHOUT disturbing the V1 pipeline.

WHAT THIS FILE PROTECTS, IN PLAIN WORDS. The project has two episode-video
renderers. The new one (`scripts/eval/render_recordings_v2.py`) is what training
and evaluation call, and it writes into a folder called `videos_v2/` — so as of
2026-09-17 these tests protect the DEFAULT render path, not a side experiment.
The previous one (`scripts/eval/render_recordings.py`) is a frozen file that
remains runnable by hand and still writes into `videos/`. The user's condition
for the whole redesign was that the old path keeps working untouched, so these
tests render the SAME recordings directory with BOTH scripts and check that the
old one's output files are byte-for-byte what they were before the new one ran,
and that the new one put nothing whatsoever inside `videos/`.

THE OTHER TWO PROPERTIES. A written MP4 must decode to exactly as many frames as
the recording has steps -- a video that silently drops a frame is the failure the
frame count exists to make visible -- and `--concat` must refuse to glue together
episodes whose dashboards are not the same shape.

WHY THE CONCAT REFUSAL IS TESTED ON THE FUNCTION RATHER THAN ON A DIRECTORY. The
plan asks for a "doctored two-param-set dir". One cannot be built: a recordings
directory has exactly ONE `run_meta.pkl`, every episode in it is rendered from
those same params, and a layout signature is a pure function of the params -- so
two episodes of one directory ALWAYS share a signature, whatever their payloads
contain. The refusal is therefore exercised directly, by handing the guard two
different signatures, and the real-directory case asserts the opposite (that a
genuine run does share one). See the Implementation Report deviation.
"""
import hashlib
import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

_REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(_REPO))
sys.path.insert(0, str(_REPO / "scripts" / "eval"))

import render_recordings_v2 as rrv2  # noqa: E402  (bare-name import, §1c)

V1_SCRIPT = _REPO / "scripts" / "eval" / "render_recordings.py"
V2_SCRIPT = _REPO / "scripts" / "eval" / "render_recordings_v2.py"

#: The campfire fixture. Gitignored, regenerated by
#: `scripts/eval/make_render_fixture_recordings.py`.
FIXTURE = _REPO / "results" / "render_audit" / "recordings" / "M4" / "M4"
_MISSING = (f"render-audit fixtures not on disk ({FIXTURE}); regenerate with "
            f"scripts/eval/make_render_fixture_recordings.py")

#: The 24-step episode -- the short one, so a full V1 + V2 render stays affordable.
EPISODE = "episode_000001.rec.gz"


def _env():
    """CPU-only, so a test can never reach for a training GPU."""
    env = dict(os.environ)
    env["JAX_PLATFORMS"] = "cpu"
    env["CUDA_VISIBLE_DEVICES"] = ""
    return env


def _run(script, *args):
    return subprocess.run([sys.executable, str(script), *map(str, args)],
                          capture_output=True, text=True, env=_env(), cwd=str(_REPO))


def _sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _tree(path):
    """Every file under `path`, relative, as {name: sha256}. Missing dir -> {}."""
    path = Path(path)
    if not path.exists():
        return {}
    return {str(p.relative_to(path)): _sha(p) for p in sorted(path.rglob("*")) if p.is_file()}


@pytest.fixture
def run_dir(tmp_path):
    """A recordings directory in the layout both scripts expect.

    `<run>/recordings/<pct>/` -- both derive their output folder as
    `<run>/videos*/<pct>/`, i.e. `rec_dir.parent.parent`.
    """
    if not (FIXTURE / "run_meta.pkl").exists():
        pytest.skip(_MISSING)
    rec = tmp_path / "run" / "recordings" / "M4"
    rec.mkdir(parents=True)
    shutil.copy2(FIXTURE / "run_meta.pkl", rec / "run_meta.pkl")
    shutil.copy2(FIXTURE / EPISODE, rec / EPISODE)
    return rec


# --------------------------------------------------------------- fast, no render


def test_there_is_no_way_to_delete_anything():
    """V1 has `--cleanup-per-episode`; V2 deliberately has none.

    The flag is how V1 can remove files, and the plan's §D5.4 requires the new
    entry point to have no deleting code path at all, so this asserts on the
    real interface (what `--help` offers) and on the absence of any deleting call
    in the source. It deliberately does NOT grep the source for the flag NAME:
    the module docstring names it to say it is absent, and a test that cannot
    tell an explanation from an implementation is not measuring anything.
    """
    src = V2_SCRIPT.read_text()
    assert 'add_argument("--cleanup-per-episode"' not in src
    assert "add_argument('--cleanup-per-episode'" not in src
    assert "unlink" not in src and "rmtree" not in src and "shutil.rm" not in src
    out = _run(V2_SCRIPT, "--help")
    assert "--cleanup-per-episode" not in out.stdout
    assert "--concat" in out.stdout and "--skip-existing" in out.stdout


def test_concat_refuses_two_different_layouts():
    """Two shapes in one video is the thing the guard exists to stop."""
    with pytest.raises(SystemExit) as exc:
        rrv2._assert_single_layout({1: "a" * 64, 2: "b" * 64})
    msg = str(exc.value)
    assert "do not share one dashboard layout" in msg
    # It must name the episodes on each side, or the refusal is unactionable.
    assert "episodes 1" in msg and "episodes 2" in msg


def test_concat_accepts_one_layout_and_returns_it():
    assert rrv2._assert_single_layout({1: "a" * 64, 2: "a" * 64}) == "a" * 64
    with pytest.raises(SystemExit):
        rrv2._assert_single_layout({})


